"""
SQLAlchemy ORM Data Models for GlobeTrotter AI.
Covers:
  1. Destination
  2. Topic (with canonical key for Level 1 deduplication)
  3. Article
  4. ResearchSource
  5. ImageAsset
  6. PublishingJob
"""

from datetime import datetime
from sqlalchemy import (
    Column,
    Integer,
    String,
    Text,
    Float,
    Boolean,
    DateTime,
    ForeignKey,
    UniqueConstraint,
    Index,
    func,
)
from sqlalchemy.orm import relationship
from app.database.base import Base


class Destination(Base):
    """
    Destinations tracked across the globe.
    """
    __tablename__ = "destinations"

    id = Column(Integer, primary_key=True, autoincrement=True)
    name = Column(String(255), nullable=False, index=True)
    country = Column(String(100), nullable=False, index=True)
    region = Column(String(100), nullable=True)
    destination_type = Column(String(100), nullable=True)  # e.g., Heritage, Mountain, Coastal, City
    description = Column(Text, nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    # Relationships
    topics = relationship("Topic", back_populates="destination_rel", cascade="all, delete-orphan")

    __table_args__ = (
        UniqueConstraint("name", "country", name="uq_destination_country"),
    )

    def __repr__(self):
        return f"<Destination(id={self.id}, name='{self.name}', country='{self.country}')>"


class Topic(Base):
    """
    Tourism topics discovered by the discovery agent.
    Includes canonical_key for Level 1 exact duplicate prevention.
    """
    __tablename__ = "topics"

    id = Column(Integer, primary_key=True, autoincrement=True)
    canonical_key = Column(String(512), unique=True, index=True, nullable=False)
    destination_id = Column(Integer, ForeignKey("destinations.id", ondelete="SET NULL"), nullable=True)
    destination = Column(String(255), nullable=False, index=True)
    country = Column(String(100), nullable=False, index=True)
    category = Column(String(100), nullable=False, index=True)  # e.g., Adventure, Heritage, Food, Nature
    proposed_title = Column(String(500), nullable=False)
    unique_angle = Column(Text, nullable=False)
    discovery_source = Column(String(100), default="ai_discovery", nullable=False)
    status = Column(
        String(50),
        default="discovered",
        index=True,
        nullable=False
    )  # discovered, researching, researched, writing, written, published, failed, rejected
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    # Relationships
    destination_rel = relationship("Destination", back_populates="topics")
    article = relationship("Article", back_populates="topic", uselist=False, cascade="all, delete-orphan")
    sources = relationship("ResearchSource", back_populates="topic", cascade="all, delete-orphan")

    __table_args__ = (
        Index("idx_topics_status_country", "status", "country"),
    )

    def __repr__(self):
        return f"<Topic(id={self.id}, canonical_key='{self.canonical_key}', status='{self.status}')>"


class Article(Base):
    """
    Full research-backed travel articles generated by the workflow.
    """
    __tablename__ = "articles"

    id = Column(Integer, primary_key=True, autoincrement=True)
    topic_id = Column(Integer, ForeignKey("topics.id", ondelete="CASCADE"), unique=True, nullable=False)
    title = Column(String(500), nullable=False)
    slug = Column(String(500), unique=True, index=True, nullable=False)
    summary = Column(Text, nullable=True)
    body_markdown = Column(Text, nullable=False)
    word_count = Column(Integer, default=0, nullable=False)
    
    # SEO Fields
    seo_title = Column(String(255), nullable=True)
    seo_description = Column(String(500), nullable=True)
    main_keyword = Column(String(100), nullable=True)

    # Quality Gate & Publishing Status
    status = Column(
        String(50),
        default="draft",
        index=True,
        nullable=False
    )  # draft, quality_passed, needs_review, published, failed
    quality_score = Column(Float, nullable=True)

    # External Website Sync
    website_post_id = Column(String(100), nullable=True, index=True)
    website_url = Column(String(1000), nullable=True)

    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    published_at = Column(DateTime(timezone=True), nullable=True)

    # Relationships
    topic = relationship("Topic", back_populates="article")
    sources = relationship("ResearchSource", back_populates="article", cascade="all, delete-orphan")
    images = relationship("ImageAsset", back_populates="article", cascade="all, delete-orphan")
    publishing_jobs = relationship("PublishingJob", back_populates="article", cascade="all, delete-orphan")

    def __repr__(self):
        return f"<Article(id={self.id}, title='{self.title[:30]}...', status='{self.status}')>"


class ResearchSource(Base):
    """
    Factual evidence and research sources backing claims in articles.
    """
    __tablename__ = "research_sources"

    id = Column(Integer, primary_key=True, autoincrement=True)
    article_id = Column(Integer, ForeignKey("articles.id", ondelete="CASCADE"), nullable=True, index=True)
    topic_id = Column(Integer, ForeignKey("topics.id", ondelete="CASCADE"), nullable=True, index=True)
    url = Column(String(2048), nullable=False)
    publisher = Column(String(255), nullable=True)
    title = Column(String(500), nullable=True)
    evidence_excerpt = Column(Text, nullable=True)
    retrieved_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    # Relationships
    article = relationship("Article", back_populates="sources")
    topic = relationship("Topic", back_populates="sources")

    def __repr__(self):
        return f"<ResearchSource(id={self.id}, publisher='{self.publisher}', url='{self.url[:40]}...')>"


class ImageAsset(Base):
    """
    Permitted media assets with attribution and licensing metadata.
    """
    __tablename__ = "image_assets"

    id = Column(Integer, primary_key=True, autoincrement=True)
    article_id = Column(Integer, ForeignKey("articles.id", ondelete="CASCADE"), nullable=False, index=True)
    image_url = Column(String(2048), nullable=False)
    local_path = Column(String(1024), nullable=True)
    provider = Column(String(100), nullable=False)  # wikimedia, unsplash, pexels
    creator = Column(String(255), nullable=True)
    license_name = Column(String(100), nullable=False)  # CC BY-SA 4.0, Unsplash License, etc.
    attribution = Column(Text, nullable=True)
    alt_text = Column(String(500), nullable=True)
    is_featured = Column(Boolean, default=False, nullable=False)
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    # Relationships
    article = relationship("Article", back_populates="images")

    def __repr__(self):
        return f"<ImageAsset(id={self.id}, provider='{self.provider}', license='{self.license_name}')>"


class PublishingJob(Base):
    """
    Idempotent publishing queue entries tracking delivery to the React website.
    """
    __tablename__ = "publishing_jobs"

    id = Column(Integer, primary_key=True, autoincrement=True)
    article_id = Column(Integer, ForeignKey("articles.id", ondelete="CASCADE"), nullable=False, index=True)
    status = Column(
        String(50),
        default="pending",
        index=True,
        nullable=False
    )  # pending, in_progress, published, failed
    attempts = Column(Integer, default=0, nullable=False)
    idempotency_key = Column(String(128), unique=True, index=True, nullable=False)
    last_error = Column(Text, nullable=True)
    scheduled_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False)

    # Relationships
    article = relationship("Article", back_populates="publishing_jobs")

    def __repr__(self):
        return f"<PublishingJob(id={self.id}, status='{self.status}', idempotency_key='{self.idempotency_key}')>"
